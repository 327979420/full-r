const params = new URLSearchParams(location.search);
const ref = params.get('ref') || '—';
const homePages = {'zh-CN': 'index.html', 'zh-TW': 'zh-hant.html', en: 'en.html', ms: 'ms.html', th: 'th.html'};
const language = document.getElementById('lang');
let saved;
try { saved = localStorage.getItem('tmgm-lang'); } catch (_) {}
const browser = (navigator.language || 'en').toLowerCase();
const fallback = browser.startsWith('zh-tw') || browser.startsWith('zh-hk') ? 'zh-TW' : browser.startsWith('zh') ? 'zh-CN' : browser.startsWith('ms') ? 'ms' : browser.startsWith('th') ? 'th' : 'en';
function setLang(lang) {
  if (!Object.hasOwn(T, lang)) lang = 'en';
  try { localStorage.setItem('tmgm-lang', lang); } catch (_) {}
  document.documentElement.lang = lang;
  language.value = lang;
  const t = T[lang];
  Object.entries(t).forEach(([key, value]) => {
    const el = document.getElementById(key);
    if (el) el.textContent = value;
  });
  language.setAttribute('aria-label', t.languageLabel);
  document.title = t.title + ' | ' + t.brand;
  document.getElementById('ref').textContent = ref;
  document.getElementById('contactBtn').href = homePages[lang] + '#contact';
  document.getElementById('homeBtn').href = homePages[lang];
}
language.addEventListener('change', event => setLang(event.target.value));
setLang(params.get('lang') || saved || fallback);
